// Helper to get formatted string: e.g. "003. Agago"
export const getDistrictOptions = () => {
  return UGANDA_DISTRICTS.map(d => `${d.code}. ${d.name}`);
};

export const getDistrictNames = () => {
  return UGANDA_DISTRICTS.map(d => d.name);
};

export const findDistrictByName = (name) => {
  if (!name) return null;
  const clean = name.replace(/^\d+\.\s*/, '').trim().toLowerCase();
  return UGANDA_DISTRICTS.find(d => d.name.toLowerCase() === clean) || null;
};

// Auto-Number Generators for Enterprise Registration Forms
export const generateAutoFarmerId = (districtName = 'Pader') => {
  const dist = findDistrictByName(districtName);
  const code = dist ? dist.code : '000';
  const randomSuffix = Math.floor(1000 + Math.random() * 9000);
  return `JRM-FMR-${code}-${randomSuffix}`;
};

export const generateAutoCoopCode = (districtName = 'Pader') => {
  const dist = findDistrictByName(districtName);
  const code = dist ? dist.code : '000';
  const randomSuffix = Math.floor(100 + Math.random() * 900);
  return `COP-UG-${code}-${randomSuffix}`;
};

export const generateAutoEmployeeId = (deptCode = 'STF') => {
  const randomSuffix = Math.floor(100 + Math.random() * 900);
  return `JER-${deptCode}-${randomSuffix}`;
};

export const generateAutoProjectCode = (prefix = 'PRJ') => {
  const year = new Date().getFullYear();
  const randomSuffix = Math.floor(100 + Math.random() * 900);
  return `${prefix}-${year}-${randomSuffix}`;
};

